"""Edits the files that OTHER patches own (one patch per file), idempotent. Run it after the release zip is built (or on a scratch copy of the
repo for tests) and again after anything regenerates one of these files (soc_mil_quests\\tools\\apply_logic.py rewrites the Lukash dialog:
run this script after it).

  python apply_shared.py [--repo <repo root>]        default: the repo this script lives in

Source data (generated by gen_all.py): patches\\soc_mil_courier\\data\\*.  Nothing here reads the SoC archives.

  freedom_duty:     configs\\gameplay\\dialogs_coop_l07_military.xml        the Lukash dialog is replaced (the courier job is added to the
                                                                          soc_mil_quests version), the Chef's dialogs are added
                    configs\\gameplay\\character_desc_coop_l07_military.xml  Pavlik, Ara, the bodyguards (one profile), the Chef
                    configs\\gameplay\\npc_profile_addon.xml                 the four profile ids
                    configs\\creatures\\spawn_sections_coop_l07_military.ltx six spawn sections (custom_data = the logic file)
                    configs\\misc\\tm_coop_l07_military.ltx                  nine task steps between the markers ';;; soc_mil_courier'
  quest_dialogs:    configs\\gameplay\\dialogs_coop_l05_bar.xml              Voronin: the Bulldog 6 order, the hand-in, the suit for a late player
  repeatable_quests: configs\\gameplay\\character_desc_coop_l05_bar.xml      Voronin gets the three actor dialogs
  installer:        changes_1.4.en.txt / .ru.txt                            one new line, the "not in the mod" sentence of soc_mil_quests goes
  soc_mil_quests, bar_soc_quests: NOTES.md                                  a marked paragraph that says the two jobs exist now
"""
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import milc_model as M

patch = os.path.dirname(here)
repo = os.path.dirname(os.path.dirname(patch))
if '--repo' in sys.argv:
    repo = os.path.abspath(sys.argv[sys.argv.index('--repo') + 1])
P = lambda *a: os.path.join(repo, 'patches', *a)
D = lambda name: open(os.path.join(patch, 'data', name), 'rb').read()
NL = '\r\n'
changed = []


def rw(path, fn, enc='cp1251'):
    if not os.path.exists(path):
        sys.exit('missing file: ' + path)
    raw = open(path, 'rb').read()
    txt = raw.decode(enc)
    new = fn(txt)
    if new != txt:
        open(path, 'wb').write(new.encode(enc))
        changed.append(os.path.relpath(path, repo))


def crlf(s):
    return s.replace('\r\n', '\n').replace('\n', NL)


def drop_dialog(t, did):
    return re.sub(r'[ \t]*<dialog id="' + re.escape(did) + r'">.*?</dialog>[ \t]*\r?\n', '', t, flags=re.S)


def dialogs_ids(xml_text):
    return re.findall(r'<dialog id="([^"]+)">', xml_text)


# ---------------------------------------------------------------------------------------------------
# 1. Army Warehouses dialogs (freedom_duty)
# ---------------------------------------------------------------------------------------------------
LUKASH = D('dialogs_l07_lukash.xml').decode('cp1251')
COOK = D('dialogs_l07_cook.xml').decode('cp1251')


def l07_dialogs(t):
    # Lukash: replace the block in place
    pat = r'[ \t]*<dialog id="' + re.escape(M.LUKASH_DIALOG) + r'">.*?</dialog>[ \t]*\r?\n'
    if re.search(pat, t, flags=re.S) is None:
        sys.exit('the Lukash dialog of soc_mil_quests is not in dialogs_coop_l07_military.xml (run soc_mil_quests\\tools\\apply_logic.py first)')
    t = re.sub(pat, lambda m: crlf(LUKASH), t, count=1, flags=re.S)
    # the Chef: out and in
    for did in dialogs_ids(COOK):
        t = drop_dialog(t, did)
    i = t.rindex('</game_dialogs>')
    return t[:i] + crlf(COOK) + t[i:]


rw(P('freedom_duty', 'gamedata', 'configs', 'gameplay', 'dialogs_coop_l07_military.xml'), l07_dialogs)

CHARS = D('characters_l07.xml').decode('cp1251')


def l07_chars(t):
    for cid in re.findall(r'<specific_character id="([^"]+)"', CHARS):
        t = re.sub(r'<specific_character id="' + re.escape(cid) + r'".*?</specific_character>[ \t]*\r?\n', '', t, flags=re.S)
    i = t.rindex('</xml>')
    return t[:i] + crlf(CHARS) + t[i:]


rw(P('freedom_duty', 'gamedata', 'configs', 'gameplay', 'character_desc_coop_l07_military.xml'), l07_chars)

PROF = D('profiles.xml').decode('ascii')


def profiles(t):
    for pid in re.findall(r'<character id="([^"]+)"', PROF):
        t = re.sub(r'[ \t]*<character id="' + re.escape(pid) + r'">.*?</character>[ \t]*\r?\n', '', t, flags=re.S)
    i = t.rindex('</xml>')
    return t[:i] + crlf(PROF) + t[i:]


rw(P('freedom_duty', 'gamedata', 'configs', 'gameplay', 'npc_profile_addon.xml'), profiles, 'utf-8')

SECT = D('spawn_sections.ltx').decode('latin-1')


def sections(t):
    for sec in re.findall(r'^\[([^\]]+)\]:stalker', SECT, flags=re.M):
        t = re.sub(r'^\[' + re.escape(sec) + r'\]:stalker[^\r\n]*\r?\n(?:(?!\[)[^\r\n]*\r?\n)*', '', t, flags=re.M)
    return t.rstrip('\r\n') + NL + NL + crlf(SECT).rstrip('\r\n') + NL


rw(P('freedom_duty', 'gamedata', 'configs', 'creatures', 'spawn_sections_coop_l07_military.ltx'), sections, 'latin-1')

TM = D('tm_tasks.ltx').decode('latin-1')
MARK_B = ';;; soc_mil_courier begin (generated by patches\\soc_mil_courier\\tools\\apply_shared.py)'
MARK_E = ';;; soc_mil_courier end'


def tm(t):
    if MARK_B in t:
        a = t.index(MARK_B)
        b = t.index(MARK_E) + len(MARK_E)
        t = t[:a].rstrip('\r\n') + NL + t[b:].lstrip('\r\n')
    blk = [NL + MARK_B, ';Army Warehouses: SoC mil_courier_job (5 objectives) and mil_freedom_rg6_task (4 objectives); texts: st_coop_soc_milc.xml']
    return t.rstrip('\r\n') + NL + NL.join(blk) + NL + crlf(TM).rstrip('\r\n') + NL + MARK_E + NL


rw(P('freedom_duty', 'gamedata', 'configs', 'misc', 'tm_coop_l07_military.ltx'), tm, 'latin-1')

