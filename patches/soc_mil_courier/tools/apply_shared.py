NOTE_B = '<!-- soc_mil_courier begin -->'
NOTE_E = '<!-- soc_mil_courier end -->'


def note(path, text):
    def fn(t):
        if NOTE_B in t:
            a = t.index(NOTE_B)
            b = t.index(NOTE_E) + len(NOTE_E)
            t = t[:a].rstrip('\r\n') + t[b:]
        nl = '\r\n' if '\r\n' in t else '\n'
        return t.rstrip('\r\n') + nl + nl + NOTE_B + nl + text.replace('\n', nl) + nl + NOTE_E + nl
    rw(path, fn, 'utf-8')


