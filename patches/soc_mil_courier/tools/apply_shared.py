def add_line(path, line, anchor, old_sentence):
    data = open(path, 'rb').read()
    nl = b'\r\n' if b'\r\n' in data else b'\n'
    enc = line.encode('utf-8')
    orig = data
    data = data.replace(old_sentence, b'')
    i = data.find(TAG)
    if i >= 0:
        j = data.find(b'\n', i)
        j = len(data) if j < 0 else j
        end = j - 1 if data[j - 1:j] == b'\r' else j
        data = data[:i] + enc + data[end:]
    else:
        i = data.find(anchor.encode('utf-8'))
        if i < 0:
            sys.exit('anchor not found in ' + path)
        data = data[:i] + enc + nl + data[i:]
    if data != orig:
        open(path, 'wb').write(data)
        changed.append(os.path.relpath(path, repo))


add_line(os.path.join(repo, 'installer', 'changes_1.4.en.txt'), EN, '- Smaller patch file', OLD_EN)
add_line(os.path.join(repo, 'installer', 'changes_1.4.ru.txt'), RU, '- Файл патча стал меньше', OLD_RU)

