VOR = D('dialogs_l05_voronin.xml').decode('cp1251')


def bar_dialogs(t):
    for did in dialogs_ids(VOR):
        t = drop_dialog(t, did)
    i = t.rindex('</game_dialogs>')
    return t[:i] + crlf(VOR) + t[i:]


rw(P('quest_dialogs', 'gamedata', 'configs', 'gameplay', 'dialogs_coop_l05_bar.xml'), bar_dialogs)

VOR_IDS = dialogs_ids(VOR)


def bar_chars(t):
    m = re.search(r'<specific_character id="bar_smart_terrain_4_duty_voronin".*?</specific_character>', t, re.S)
    if m is None:
        sys.exit('Voronin is not in character_desc_coop_l05_bar.xml')
    blk = m.group(0)
    for d in VOR_IDS:
        blk = re.sub(r'[ \t]*<actor_dialog>' + re.escape(d) + r'</actor_dialog>[ \t]*\r?\n', '', blk)
    ind = re.search(r'([ \t]*)<actor_dialog>actor_break_dialog</actor_dialog>', blk)
    if ind is None:
        sys.exit('Voronin has no actor_break_dialog line')
    add = ''.join(ind.group(1) + '<actor_dialog>%s</actor_dialog>' % d + NL for d in VOR_IDS)
    blk = blk[:ind.start()] + add + blk[ind.start():]
    return t[:m.start()] + blk + t[m.end():]


rw(P('repeatable_quests', 'gamedata', 'configs', 'gameplay', 'character_desc_coop_l05_bar.xml'), bar_chars)

