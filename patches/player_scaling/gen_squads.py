# Generates gamedata/configs/misc/squad_descr_pscale.ltx: for every hostile, fully generic squad that has a fixed
# target_smart, a copy "<section>_ps" without story_id and on_death. player_scaling.script creates these as
# reinforcement squads (the original keeps its story_id, a second squad with the same story_id aborts the server).
# Usage: python -I gen_squads.py <Shadow of COOP source dir containing gamedata.db0> [out.ltx]
import os, re, sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "gamedata", "configs", "misc", "squad_descr_pscale.ltx")
HOSTILE = {"monster", "monster_predatory_day", "monster_predatory_night", "monster_vegetarian", "monster_zombied_day",
           "monster_zombied_night", "monster_special", "bandit", "killer", "monolith", "zombied"}
SKIP_FILES = ("squad_descr_coop_l11_sarcofag.ltx",)   # FPS: the Sarcophagus is excluded (see skip_levels in player_scaling.ltx)

def sections(path):
    cur, body, res = None, [], []
    for raw in open(path, "rb").read().decode("latin-1").splitlines():
        m = re.match(r"^\[([^\]]+)\](:\s*(\w+))?", raw)
        if m:
            if cur: res.append((cur, parent, body))
            cur, parent, body = m.group(1), m.group(3), []
        elif cur is not None:
            body.append(raw)
    if cur: res.append((cur, parent, body))
    return res

def kv(body):
    d = {}
    for l in body:
        l = l.split(";")[0].strip()
        if "=" in l:
            k, v = l.split("=", 1)
            d[k.strip()] = v.strip()
    return d

named = set()
cdir = os.path.join(src, "gamedata.db0", "configs", "creatures")
for f in os.listdir(cdir):
    if f.startswith("spawn_sections"):
        for name, parent, body in sections(os.path.join(cdir, f)):
            if "story_id" in kv(body):
                named.add(name)
mdir = os.path.join(src, "gamedata.db0", "configs", "misc")
lines = ["; GENERATED by gen_squads.py. Reinforcement copies of hostile generic squads (no story_id, no on_death).",
         "; Used only by player_scaling.script. Do not edit by hand."]
n = 0
for f in sorted(os.listdir(mdir)):
    if not re.match(r"squad_descr_coop_.*\.ltx$", f) or f in SKIP_FILES:
        continue
    for name, parent, body in sections(os.path.join(mdir, f)):
        d = kv(body)
        if d.get("faction") not in HOSTILE or "target_smart" not in d:
            continue
        pool = [x.strip() for x in (d.get("npc", "") + "," + d.get("npc_random", "")).split(",") if x.strip()]
        if not pool or any(p in named for p in pool):
            continue
        if parent != "online_offline_group" or "_dead" in name or "dead_" in name:
            continue
        keep = []
        for l in body:
            key = l.split("=")[0].strip()
            if key in ("story_id", "on_death") or l.strip().startswith(";") or not l.strip():
                continue
            keep.append(l)
        lines.append("")
        lines.append("[%s_ps]:online_offline_group" % name)
        lines += keep
        n += 1
with open(out, "wb") as fh:
    fh.write(("\r\n".join(lines) + "\r\n").encode("latin-1"))
print("wrote", out, n, "clone sections")
