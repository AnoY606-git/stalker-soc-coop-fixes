# Generates the quest_dialogs patch: the "About the job..." (idle) and "I want to cancel the order..." (fail) dialogs of the
# quest givers only show when that giver has a quest running. Adds one dialog-level <precondition> to each of those dialogs
# and writes gamedata/scripts/coop_quest_dialogs.script with the flag rules taken from the dialogs' own answer phrases.
# Usage: python gen_quest_dialogs.py <mod source gamedata.db0 folder>
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.dirname(os.path.dirname(here))
src = sys.argv[1]
files = ['dialogs_coop_l01_escape.xml', 'dialogs_coop_l05_bar.xml', 'dialogs_coop_l08_yantar.xml']
out_dir = os.path.join(here, 'gamedata', 'configs', 'gameplay')
rules = {}
# a finished kill quest has no hand-in phrase, so its cancel phrase would stay open: add the quest's done flag (repeatable_quests table)
done_of = {}
ltx = os.path.join(repo, 'patches', 'repeatable_quests', 'gamedata', 'configs', 'misc', 'coop_repeat_quests.ltx')
cur = {}
for line in open(ltx, encoding='cp1251').read().splitlines() + ['[end]']:
    line = line.split(';')[0].strip()
    if line.startswith('['):
        if 'accept' in cur and 'done' in cur:
            done_of[cur['accept']] = cur['done']
        cur = {}
    elif '=' in line:
        k, v = [x.strip() for x in line.split('=', 1)]
        cur[k] = v

for name in files:
    # another patch may already ship this file: build on top of it
    base = os.path.join(repo, 'patches', 'cordon', 'gamedata', 'configs', 'gameplay', name)
    if not os.path.isfile(base):
        base = os.path.join(src, 'configs', 'gameplay', name)
    data = open(base, 'rb').read()
    def patch(m):
        did = m.group(1).decode()
        body = m.group(0)
        alts = []
        for ph in re.findall(rb'<phrase id="\d+">(.*?)</phrase>', body, re.S):
            has = [h.decode() for h in re.findall(rb'<has_flag>\s*(\S+?)\s*</has_flag>', ph)]
            dont = [h.decode() for h in re.findall(rb'<dont_has_flag>\s*(\S+?)\s*</dont_has_flag>', ph)]
            for h in has:
                if h in done_of and done_of[h] not in dont:
                    dont.append(done_of[h])
            if has and not set(has) & set(dont):
                alts.append((has, dont))
        rules[did] = alts
        head = m.group(0)[:m.end(2) - m.start(0)]
        return head + b'\r\n        <precondition>coop_quest_dialogs.active_' + did.encode() + b'</precondition>' + body[len(head):]
    data, n = re.subn(rb'<dialog id="(\w+_secondary_quests_(?:fail|idle)_dialog)"(>)(.*?)</dialog>', patch, data, flags=re.S)
    print(name, 'dialogs patched:', n)
    if name == 'dialogs_coop_l05_bar.xml':
        # the technician-parts dialogs of Plyushkin are cut (patches/no_tech_parts)
        data = re.sub(rb'[ \t]*<dialog id="bar_smart_terrain_10_stalker_plyushkin_(?:what_kind_of_junk_is_needed|hand_over_the_trash)_dialog">.*?</dialog>[ \t]*\r?\n', b'', data, flags=re.S)
    open(os.path.join(out_dir, name), 'wb').write(data)

lines = ['-- Generated by patches/quest_dialogs/gen_quest_dialogs.py, do not edit by hand.',
         '-- The quest givers\' "About the job..." and "I want to cancel the order..." dialogs only show while one of their quests runs:',
         '-- a dialog is available when at least one of its answer phrases is (all has_flag set, no dont_has_flag set).',
         '', 'local rules = {']
for did, alts in sorted(rules.items()):
    lines.append('\t%s = {' % did)
    for has, dont in alts:
        lines.append('\t\t{ has = { %s }, dont = { %s } },' % (', '.join('"%s"' % h for h in has), ', '.join('"%s"' % d for d in dont)))
    lines.append('\t},')
lines += ['}', '',
          'local function any_open(alts)',
          '\tfor _, alt in ipairs(alts) do',
          '\t\tlocal ok = true',
          '\t\tfor _, f in ipairs(alt.has) do if not story_flags.has_flag(f) then ok = false break end end',
          '\t\tif ok then',
          '\t\t\tfor _, f in ipairs(alt.dont) do if story_flags.has_flag(f) then ok = false break end end',
          '\t\tend',
          '\t\tif ok then return true end',
          '\tend',
          '\treturn false',
          'end', '']
for did in sorted(rules):
    lines.append('function active_%s(first_speaker, second_speaker) return any_open(rules.%s) end' % (did, did))
open(os.path.join(here, 'gamedata', 'scripts', 'coop_quest_dialogs.script'), 'w', newline='\r\n').write('\n'.join(lines) + '\n')
print('rules:', {k: len(v) for k, v in rules.items()})

