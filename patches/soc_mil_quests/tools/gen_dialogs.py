"""Dialog xml and the PDA archive script of patch soc_mil_quests, generated from mil_model.py.
  python gen_dialogs.py          writes gamedata\\scripts\\coop_soc_mil_say.script
apply_logic.py imports dialog_xml() to put the dialogs into the Army Warehouses dialog file."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import mil_model as M

NL = '\r\n'
MOD_MAX = 'coop_pda_phrases.say__' + M.MAX_GREETING


def say_name(key, pid):
    return 'say_%s_%s' % (key, pid)


def phrase_xml(key, d, ph):
    pid, spk, nxt, pre, flags, acts = ph
    s = ['            <phrase id="%s">' % pid]
    if spk == M.H:
        s.append('                <text />')
    else:
        if key == 'mx' and pid == '31':
            s.append('                <action>%s</action>' % MOD_MAX)
            s.append('                <text>%s</text>' % M.MAX_GREETING)
        else:
            s.append('                <action>coop_soc_mil_say.%s</action>' % say_name(key, pid))
            s.append('                <text>coop_soc_mil_%s_%s</text>' % (key, pid))
    for p in pre:
        s.append('                <precondition>coop_soc_mil.%s</precondition>' % p)
    for a in acts:
        s.append('                <action>coop_soc_mil.%s</action>' % a)
    for f in flags:
        s.append('                <give_flag>%s</give_flag>' % f)
    if not nxt and spk != M.H:
        s.append('                <action>dialogs.break_dialog</action>')
    for n in nxt:
        s.append('                <next>%s</next>' % n)
    s.append('            </phrase>')
    return s


def dialog_xml(key):
    d = M.DIALOGS[key]
    L = ['    <dialog id="%s">' % d['id'], '        <phrase_list>']
    for ph in d['phrases']:
        L += phrase_xml(key, d, ph)
    L += ['        </phrase_list>', '    </dialog>']
    return NL.join(L) + NL


def say_script():
    L = ['-------------------------------------------------------------------------------------------------------',
         '-- GENERATED by patches\\soc_mil_quests\\tools\\gen_dialogs.py: the PDA archive line of every phrase of the SoC Army Warehouses dialogs',
         '-- (Lukash, Max, Skull, Cap). Same helper calls as the Barkeep / Garbage dialogs of the other SoC quest patches.',
         '-------------------------------------------------------------------------------------------------------',
         '',
         'local SPEAKER = {']
    ids = []
    for key, d in M.DIALOGS.items():
        for pid, spk, nxt, pre, flags, acts in d['phrases']:
            if spk == M.H or (key == 'mx' and pid == '31'):
                continue
            ids.append((key, pid, spk))
    for key, pid, spk in ids:
        L.append('\t%s_%s = "%s",' % (key, pid, spk))
    L += ['}', '', 'local function emit(id, first, second)',
          '\tlocal tid = "coop_soc_mil_" .. id',
          '\tpcall(function() coop_pda_phrases.phrase_speaker[tid] = SPEAKER[id] end)',
          '\tpcall(function() coop_pda_archive_sync.emit_phrase(first, second, tid) end)',
          'end', '']
    for key, pid, spk in ids:
        L.append('function %s(a, b) emit("%s_%s", a, b) end' % (say_name(key, pid), key, pid))
    return '\r\n'.join(L) + '\r\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(here), 'gamedata', 'scripts', 'coop_soc_mil_say.script')
    open(out, 'wb').write(say_script().encode('ascii'))
    print('wrote', out)
