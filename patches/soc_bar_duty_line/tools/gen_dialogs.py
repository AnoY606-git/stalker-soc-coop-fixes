"""Dialog xml and the PDA archive script of patch soc_bar_duty_line, generated from duty_model.py.
  python gen_dialogs.py
writes gamedata\\configs\\gameplay\\dialogs_coop_soc_duty.xml (registered by tools\\apply_shared.py) and gamedata\\scripts\\coop_soc_duty_say.script."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import duty_model as M

NL = '\r\n'
GD = os.path.join(os.path.dirname(here), 'gamedata')


def say_name(key, pid):
    return 'say_%s_%s' % (key, pid)


def phrase_xml(key, d, ph):
    pid, spk, nxt, pre, flags, acts = ph
    s = ['            <phrase id="%s">' % pid]
    if spk == M.H:
        s.append('                <text />')
    else:
        s.append('                <action>coop_soc_duty_say.%s</action>' % say_name(key, pid))
        s.append('                <text>coop_soc_duty_%s_%s</text>' % (key, pid))
    for p in pre:
        s.append('                <precondition>coop_soc_duty.%s</precondition>' % p)
    for a in acts:
        s.append('                <action>coop_soc_duty.%s</action>' % a)
    for f in flags:
        s.append('                <give_flag>%s</give_flag>' % f)
    if not nxt and spk != M.H and not d.get('keep_open'):
        s.append('                <action>dialogs.break_dialog</action>')
    for n in nxt:
        s.append('                <next>%s</next>' % n)
    s.append('            </phrase>')
    return s


def dialog_xml(key):
    d = M.DIALOGS[key]
    L = ['    <dialog id="%s">' % d['id']]
    if d.get('pre'):
        L.append('        <precondition>coop_soc_duty.%s</precondition>' % d['pre'])
    L.append('        <phrase_list>')
    for ph in d['phrases']:
        L += phrase_xml(key, d, ph)
    L += ['        </phrase_list>', '    </dialog>']
    return NL.join(L) + NL


def xml_file():
    head = ['<?xml version="1.0" encoding="windows-1251" ?>', '<game_dialogs>',
            '    <!-- GENERATED by patches\\soc_bar_duty_line\\tools\\gen_dialogs.py from duty_model.py: the Bar Duty / Freedom line of the original SoC -->']
    return NL.join(head) + NL + ''.join(dialog_xml(k) for k in M.DIALOGS) + '</game_dialogs>' + NL


def say_script():
    L = ['-------------------------------------------------------------------------------------------------------',
         '-- GENERATED by patches\\soc_bar_duty_line\\tools\\gen_dialogs.py: the PDA archive line of every phrase of the Duty line dialogs',
         '-- (Voronin, Petrenko, gate commander, Ivantsov, the Barkeep jobs). Same helper calls as the other SoC quest patches.',
         '-------------------------------------------------------------------------------------------------------',
         '',
         'local SPEAKER = {']
    ids = []
    for key, d in M.DIALOGS.items():
        for pid, spk, nxt, pre, flags, acts in d['phrases']:
            if spk == M.H:
                continue
            ids.append((key, pid, spk))
    for key, pid, spk in ids:
        L.append('\t%s_%s = "%s",' % (key, pid, spk))
    L += ['}', '', 'local function emit(id, first, second)',
          '\tlocal tid = "coop_soc_duty_" .. id',
          '\tpcall(function() coop_pda_phrases.phrase_speaker[tid] = SPEAKER[id] end)',
          '\tpcall(function() coop_pda_archive_sync.emit_phrase(first, second, tid) end)',
          'end', '']
    for key, pid, spk in ids:
        L.append('function %s(a, b) emit("%s_%s", a, b) end' % (say_name(key, pid), key, pid))
    return NL.join(L) + NL


if __name__ == '__main__':
    p = os.path.join(GD, 'configs', 'gameplay', 'dialogs_coop_soc_duty.xml')
    os.makedirs(os.path.dirname(p), exist_ok=True)
    open(p, 'wb').write(xml_file().encode('cp1251'))
    q = os.path.join(GD, 'scripts', 'coop_soc_duty_say.script')
    os.makedirs(os.path.dirname(q), exist_ok=True)
    open(q, 'wb').write(say_script().encode('ascii'))
    print('wrote', p)
    print('wrote', q)
