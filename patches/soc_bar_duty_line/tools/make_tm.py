"""Task file of patch soc_bar_duty_line: gamedata\\configs\\misc\\tm_coop_soc_duty.ltx (generated from duty_model.TASKS; tools\\apply_shared.py adds the
#include to task_manager.ltx). Text ids are coop_soc_duty_<task id>_name and _s<step> (tools\\gen_text.py)."""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import duty_model as M

GD = os.path.join(os.path.dirname(here), 'gamedata')
L = ['; Bar Duty / Freedom line of the original SoC (patch soc_bar_duty_line). GENERATED by tools\\make_tm.py from duty_model.py.',
     '; Every task is given to every player by coop_soc_duty.script while its stage is open; it completes with the flag below, so a finished task never returns.',
     '']
for t in M.TASKS:
    base = 'coop_soc_duty_' + t['id']
    descr, target = [], []
    for i, (cond, txt, tgt) in enumerate(t['steps']):
        pre = '{%s} ' % cond if cond else ''
        descr.append('%s%s_s%d' % (pre, base, i))
        target.append('%s%s' % (pre, tgt))
    L += ['[%s]' % t['id'],
          '%-40s= %s' % ('icon', t['icon']), '%-40s= 200' % 'prior', '%-40s= true' % 'storyline',
          '%-40s= %s_name' % ('title', base),
          '%-40s= %s' % ('descr', ', '.join(descr)),
          '%-40s= %s' % ('target', ', '.join(target)),
          '%-40s= %s' % ('condlist_0', t['complete']), '']
p = os.path.join(GD, 'configs', 'misc', 'tm_coop_soc_duty.ltx')
os.makedirs(os.path.dirname(p), exist_ok=True)
data = '\r\n'.join(L).encode('ascii')
old = open(p, 'rb').read() if os.path.exists(p) else None
if old != data:
    open(p, 'wb').write(data)
    print('written', p)
else:
    print('unchanged', p)
