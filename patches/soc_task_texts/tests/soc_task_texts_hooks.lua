local function norm(s)
	s = tostring(s or "")
	s = string.gsub(s, "\\n", " ")
	s = string.gsub(s, "%s+", " ")
	s = string.gsub(s, "^ ", "")
	s = string.gsub(s, " $", "")
	return s
end

qa.once("soc_task_texts", function(t, lo)
	if _G.__qa_soc_task_texts then return end
	_G.__qa_soc_task_texts = true
	local lang = L.language()
	local col = (lang == "rus") and 2 or 3
	local bad = 0
	for _, e in ipairs(EXPECT) do
		local ok, got = pcall(function() return game.translate_string(e[1]) end)
		local pass = ok and norm(got) == norm(e[col])
		if not pass then bad = bad + 1 end
		qa.assert("TT " .. lang .. " " .. e[1], pass, pass and "" or ("want [" .. norm(e[col]) .. "] got [" .. norm(got) .. "]"))
	end
	qa.assert("TT all " .. #EXPECT .. " ids translate to the SoC text (" .. tostring(lang) .. ")", bad == 0, bad .. " wrong")
end)
