#!/usr/bin/env python3
"""Builds gamedata/scripts/stash_loot_kinds.script: which add-on boxes get the FOSTER fallback rule.

kinds[level][object name] = "w" (wooden breakable box) | "m" (metal breakable box) | "i" (plain inventory box)

Only boxes that have NO original SoC loot data are listed: not in stash_loot_data.boxes, no own [drop_box],
no [logic] scheme. The visual decides wood or metal (the engine script API has no reliable visual getter, so the
table is made offline from level.spawn). Inventory boxes: only those with no custom data at all (the stash boxes
carry [spawn] and are filled by the add-on author; story_object boxes belong to quests).

  python gen_box_kinds.py [--addon <addon_unpacked>]
"""
import argparse, collections, os, re, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'tools'))
import xdb  # noqa: E402

WOOD = ('box_wood_01', 'box_wood_02', 'box_wood_tara', 'box_1a', 'box_1b')
METAL = ('box_metall_01', 'box_lab_03')


def read_level_spawns(addon):
    for dbn in ('gamedata.db0', 'gamedata.db1'):
        p = os.path.join(addon, dbn)
        f = open(p, 'rb')
        for name, rs, cs, ptr in xdb.index(f, 0, os.path.getsize(p)):
            m = re.match(r'levels\\(coop_[^\\]+)\\level\.spawn$', name)
            if not m:
                continue
            f.seek(ptr)
            d = f.read(cs)
            if rs != cs:
                d = xdb.lzo1x(d, rs)
            yield m.group(1), d


def data_names(path):
    names, cur, inb = collections.defaultdict(set), None, False
    for line in open(path, encoding='latin1').read().split('\n'):
        if line.startswith('boxes = {'):
            inb = True
            continue
        if not inb:
            continue
        m = re.match(r'\t(coop_\w+) = \{', line)
        if m:
            cur = m.group(1)
            continue
        m = re.match(r'\t\t\["([^"]+)"\]', line)
        if m:
            names[cur].add(m.group(1))
    return names


def main():
    ap = argparse.ArgumentParser()
    dl = os.path.join(os.path.expanduser('~'), 'Downloads')
    ap.add_argument('--addon', default=os.path.join(dl, 'Shadow of COOP 8.0', 'addon_unpacked'))
    ap.add_argument('--out', default=os.path.join(HERE, '..', 'gamedata', 'scripts', 'stash_loot_kinds.script'))
    a = ap.parse_args()
    known = data_names(os.path.join(HERE, '..', 'gamedata', 'scripts', 'stash_loot_data.script'))
    kinds = collections.defaultdict(dict)
    for lv, d in sorted(read_level_spawns(a.addon)):
        o = 0
        while o + 8 <= len(d):
            _, s = struct.unpack_from('<II', d, o)
            o += 8
            c = d[o:o + s]
            o += s
            mm = re.match(rb'\x01\x00([^\x00]*)\x00([^\x00]*)\x00', c)
            if not mm:
                continue
            sec, nm = mm.group(1).decode('latin1'), mm.group(2).decode('latin1')
            if sec not in ('physic_destroyable_object', 'inventory_box'):
                continue
            cd = re.search(rb'(\[[A-Za-z_0-9.]+\][\x09\x0a\x0d\x20-\x7e]*)', c[mm.end():])
            secs = re.findall(r'^\[([^\]]+)\]', cd.group(1).decode('latin1'), re.M) if cd else []
            if sec == 'inventory_box':
                if not secs:
                    kinds[lv][nm] = 'i'
                continue
            if nm in known[lv] or 'drop_box' in secs or 'logic' in secs or 'story_object' in secs:
                continue
            v = re.findall(rb'(?:dynamics|physics)\\[\w\\]+', c)
            vis = v[0].decode().split('\\')[-1] if v else ''
            if vis in WOOD:
                kinds[lv][nm] = 'w'
            elif vis in METAL:
                kinds[lv][nm] = 'm'
    L = ['-- GENERATED by patches/stash_loot/tools/gen_box_kinds.py, do not edit by hand.',
         '-- kinds[level][object name] = "w" wooden box | "m" metal box | "i" plain inventory box.',
         '-- Boxes without original SoC loot data; they use the chances of configs/misc/box_loot.ltx.', '',
         'kinds = {']
    tot = collections.Counter()
    for lv in sorted(kinds):
        L.append('\t%s = {' % lv)
        for nm, k in sorted(kinds[lv].items()):
            L.append('\t\t["%s"]="%s",' % (nm, k))
            tot[k] += 1
        L.append('\t},')
    L.append('}')
    out = os.path.abspath(a.out)
    open(out, 'wb').write(('\r\n'.join(L) + '\r\n').encode('latin1'))
    for lv in sorted(kinds):
        print('%-30s %s' % (lv, dict(collections.Counter(kinds[lv].values()))))
    print('total', dict(tot), 'wrote', out)


if __name__ == '__main__':
    main()
