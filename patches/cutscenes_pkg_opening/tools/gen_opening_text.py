#!/usr/bin/env python3
"""Generate the subtitle / hint tutorial blocks and string tables of package "opening".

usage: python gen_opening_text.py            (writes into ../gamedata)
Input : opening_text.json  (subtitle segments per voice line, hint texts; en + ru)
Output: gamedata/configs/ui/coop_scn_opening.xml
        gamedata/configs/text/eng/st_coop_scn_opening.xml   (ASCII)
        gamedata/configs/text/rus/st_coop_scn_opening.xml   (windows-1251)
No em dashes, CRLF line ends.
"""
import json, math, os, sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
GD = os.path.join(os.path.dirname(HERE), "gamedata")
data = json.load(open(os.path.join(HERE, "opening_text.json"), encoding="utf-8"))

strings = []   # (id, en, ru)
blocks = []

SUB = ('\t\t\t<auto_static start_time="%d" length_sec="%d" x="112" y="632" width="800" height="110" '
       'alignment="c" stretch="1">\n\t\t\t\t<text font="letterica18" r="238" g="238" b="238" a="255" align="c">%s</text>\n\t\t\t</auto_static>\n')

for key, ln in data["lines"].items():
    segs = ln["segs"]
    total = int(math.ceil(ln["dur"])) + 1
    body = ""
    for i, s in enumerate(segs):
        sid = "scn_opening_%s_%d" % (key, i + 1)
        strings.append((sid, s["en"], s["ru"]))
        t0 = int(round(s["t0"]))
        t1 = int(round(segs[i + 1]["t0"])) if i + 1 < len(segs) else total
        if t1 <= t0:
            t1 = t0 + 1
        body += SUB % (t0, t1 - t0, sid)
    blocks.append(
        "\t<scn_opening_sub_%s>\n\t\t<global_wnd/>\n\t\t<item>\n\t\t\t<length_sec>%d</length_sec>\n"
        "\t\t\t<pause_state>off</pause_state>\n\t\t\t<can_be_stopped>off</can_be_stopped>\n\t\t\t<grab_input>0</grab_input>\n"
        "\t\t\t<main_wnd>\n%s\t\t\t</main_wnd>\n\t\t</item>\n\t</scn_opening_sub_%s>\n" % (key, total, body, key))

HINT = ('\t\t\t<auto_static start_time="0" length_sec="%d" x="640" y="440" width="360" height="280" alignment="c" stretch="1">\n'
        '\t\t\t\t<text font="graffiti22" r="225" g="225" b="250" a="255">%s</text>\n\t\t\t</auto_static>\n')
for key, h in data["hints"].items():
    sid = "scn_opening_hint_%s" % key
    strings.append((sid, h["en"], h["ru"]))
    sec = h["sec"]
    blocks.append(
        "\t<scn_opening_hint_%s>\n\t\t<global_wnd/>\n\t\t<item>\n\t\t\t<length_sec>%d</length_sec>\n"
        "\t\t\t<pause_state>off</pause_state>\n\t\t\t<can_be_stopped>off</can_be_stopped>\n\t\t\t<grab_input>0</grab_input>\n"
        "\t\t\t<main_wnd>\n%s\t\t\t</main_wnd>\n\t\t</item>\n\t</scn_opening_hint_%s>\n" % (key, sec, HINT % (sec, sid), key))

tip = data["misc"]["tip_talk"]
strings.append(("scn_opening_tip_talk", tip["en"], tip["ru"]))
blocks.append(
    "\t<scn_opening_tip_talk>\n\t\t<global_wnd/>\n\t\t<item>\n\t\t\t<length_sec>5</length_sec>\n"
    "\t\t\t<pause_state>off</pause_state>\n\t\t\t<can_be_stopped>off</can_be_stopped>\n\t\t\t<grab_input>0</grab_input>\n"
    "\t\t\t<main_wnd>\n%s\t\t\t</main_wnd>\n\t\t</item>\n\t</scn_opening_tip_talk>\n" % (HINT % (5, "scn_opening_tip_talk")))
off = data["misc"]["pda_offer"]
strings.append(("scn_opening_pda_offer", off["en"], off["ru"]))


def w(path, text, enc):
    assert "—" not in text and "–" not in text, "dash in " + path
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(text.replace("\r\n", "\n").replace("\n", "\r\n").encode(enc))


w(os.path.join(GD, "configs", "ui", "coop_scn_opening.xml"),
  "<!-- coop_scn_opening: subtitle, tip and hint tutorial blocks of package opening. Generated by tools/gen_opening_text.py. -->\n\n"
  + "\n".join(blocks), "utf-8")

for lang, enc, idx in (("eng", "utf-8", 1), ("rus", "windows-1251", 2)):
    out = '<?xml version="1.0" encoding="%s"?>\n<string_table>\n' % ("UTF-8" if enc == "utf-8" else "windows-1251")
    for s in strings:
        out += '\t<string id="%s"><text>%s</text></string>\n' % (s[0], escape(s[idx]))
    out += "</string_table>\n"
    w(os.path.join(GD, "configs", "text", lang, "st_coop_scn_opening.xml"), out, enc)
print("strings:", len(strings), "blocks:", len(blocks))
